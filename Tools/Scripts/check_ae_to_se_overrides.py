#!/usr/bin/env python3
"""Keep the 1.5.97 override table a valid input to the map that ships.

`GameFiles/Skyrim/SKSE/Plugins/versionlib-ae-to-se-1-5-97-0.map` is what a 1.5.x
runtime actually loads: it translates AE-era address library ids (the ones the
client resolves through) into 1.5.97 RVA offsets. It is generated by
`Tools/Scripts/gen_ae_to_se_map.py`, which joins an AE-side name table to an
SE-side one by symbol name and then applies `--overrides` on top.

`Tools/ida/st_overrides_all.tsv` is that override table: 3,678 hand-checked
id -> RVA pairs, and the reason the shipped map has no holes. Its reader is

    table[ae_id] = se_offset

so a repeated id silently keeps the last value. That is how this file came to
hold two different RVAs for id 35086 - `0x567a89` early on and `0x567a80` at the
end - with the shipped map agreeing with whichever happened to be last. Both
were plausible integers, so nothing complained; the only way to tell them apart
is to ask the 1.5.97 address library, where `0x567a80` is a function start and
`0x567a89` is nine bytes into it, past the `test rdx,rdx / je` prologue.

Id 35086 is live: `Actor.cpp` resolves `TApplyActorEffect` through it, so a
value pointing into the middle of a function is a call into the wrong place.

The checks here are the ones that would have caught it, and they need only files
this repository already ships:

  * every id appears once - a repeat means the reader is choosing silently;
  * every RVA is a function start in `version-1-5-97-0.bin`, the library the
    client loads on that build, except for the data/RTTI locators that live past
    the end of `.text`;
  * every value agrees with the map that ships, since the map is generated from
    this file.

    python Tools/Scripts/check_ae_to_se_overrides.py          # the gate
    python Tools/Scripts/check_ae_to_se_overrides.py --list   # show what is checked
"""

from __future__ import annotations

import argparse
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
OVERRIDE_DIR = ROOT / 'Tools' / 'ida'
SHIPPED_MAP = ROOT / 'GameFiles' / 'Skyrim' / 'SKSE' / 'Plugins' / 'versionlib-ae-to-se-1-5-97-0.map'
SE_LIBRARY = ROOT / 'GameFiles' / 'Skyrim' / 'SKSE' / 'Plugins' / 'version-1-5-97-0.bin'

# Every override file the documented regeneration passes to gen_ae_to_se_map.py,
# in the order it passes them.
#
# The first version of this gate read only st_overrides_all.tsv, because that is
# where the defect it was written for lived. That is the same scope mistake as
# check_ostimng_versions.py (section 113) and check_wire_symmetry.py (section
# 116): the scan root was the place the problem was found rather than the rule.
# The rule is "every file the map is generated from", and the README lists three.
OVERRIDE_FILES = ['st_overrides.txt', 'st_overrides_graph.txt', 'st_overrides_all.tsv']

# Rows whose RVA is deliberately not a function start, and ids deliberately kept
# out of the shipped map, each with the reason. Keyed by "file:id".
ALLOWED_NON_START: dict[str, str] = {}

# st_overrides_graph.txt carries BSRandom::GetGenerator, which the README says is
# "not yet folded into the map" and must stay that way - the file is the evidence
# log, the map is what ships. So an id in an override file but not in the map is
# only a failure when it is not this one.
ALLOWED_ABSENT: dict[str, str] = {
    'st_overrides_graph.txt:14774': 'BSRandom::GetGenerator, documented as not yet folded into the map',
}


def read_library(path: pathlib.Path) -> dict[int, int]:
    """A pre-AE (format 1) address library as {id: rva}."""
    data = path.read_bytes()
    if len(data) < 16:
        return {}
    (fmt,) = struct.unpack_from('<i', data, 0)
    if fmt != 1:
        return {}

    off = 4 + 16  # format + four version ints
    (name_len,) = struct.unpack_from('<i', data, off)
    off += 4 + max(name_len, 0)
    ptr_size, count = struct.unpack_from('<ii', data, off)
    off += 8

    out: dict[int, int] = {}
    prev_id = 0
    prev_off = 0
    for _ in range(count):
        type_byte = data[off]
        off += 1
        low, high = type_byte & 0xF, type_byte >> 4

        if low == 0:
            (q1,) = struct.unpack_from('<Q', data, off)
            off += 8
        elif low == 1:
            q1 = prev_id + 1
        elif low == 2:
            q1 = prev_id + data[off]
            off += 1
        elif low == 3:
            q1 = prev_id - data[off]
            off += 1
        elif low == 4:
            (d,) = struct.unpack_from('<H', data, off)
            off += 2
            q1 = prev_id + d
        elif low == 5:
            (d,) = struct.unpack_from('<H', data, off)
            off += 2
            q1 = prev_id - d
        elif low == 6:
            (q1,) = struct.unpack_from('<H', data, off)
            off += 2
        else:
            (q1,) = struct.unpack_from('<I', data, off)
            off += 4

        base = prev_off // ptr_size if (high & 8) else prev_off
        kind = high & 7
        if kind == 0:
            (q2,) = struct.unpack_from('<Q', data, off)
            off += 8
        elif kind == 1:
            q2 = base + 1
        elif kind == 2:
            q2 = base + data[off]
            off += 1
        elif kind == 3:
            q2 = base - data[off]
            off += 1
        elif kind == 4:
            (d,) = struct.unpack_from('<H', data, off)
            off += 2
            q2 = base + d
        elif kind == 5:
            (d,) = struct.unpack_from('<H', data, off)
            off += 2
            q2 = base - d
        elif kind == 6:
            (q2,) = struct.unpack_from('<H', data, off)
            off += 2
        else:
            (q2,) = struct.unpack_from('<I', data, off)
            off += 4

        if high & 8:
            q2 *= ptr_size
        out[q1] = q2
        prev_off, prev_id = q2, q1
    return out


def overrides(name: str) -> list[tuple[int, int, int]]:
    """(line number, id, rva) for every data row of one override file."""
    out: list[tuple[int, int, int]] = []
    path = OVERRIDE_DIR / name
    if not path.is_file():
        return out
    for number, line in enumerate(path.read_text(encoding='utf-8').splitlines(), start=1):
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) < 2:
            continue
        try:
            out.append((number, int(parts[0], 0), int(parts[1], 0)))
        except ValueError:
            continue
    return out


def shipped() -> dict[int, int]:
    out: dict[int, int] = {}
    if not SHIPPED_MAP.is_file():
        return out
    for line in SHIPPED_MAP.read_text(encoding='utf-8').splitlines():
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        parts = line.split()
        if len(parts) >= 2:
            try:
                out[int(parts[0], 0)] = int(parts[1], 0)
            except ValueError:
                continue
    return out


def check(failures: list[str], warnings: list[str]) -> int:
    if not SE_LIBRARY.is_file():
        failures.append(
            f'{SE_LIBRARY.relative_to(ROOT).as_posix()} is missing; no override row can be '
            f'validated against the library it has to agree with')
        return 0

    library = read_library(SE_LIBRARY)
    if not library:
        failures.append(
            f'{SE_LIBRARY.relative_to(ROOT).as_posix()} is not a pre-AE (format 1) library, so no '
            f'row can be validated against it')
        return 0

    starts = set(library.values())
    # The highest RVA any function has; anything past it is data, which is what
    # the AE ids above ~400000 name.
    text_end = max(starts)
    shipped_map = shipped()

    checked = 0
    contributed: dict[str, int] = {}

    for name in OVERRIDE_FILES:
        path = OVERRIDE_DIR / name
        if not path.is_file():
            failures.append(
                f'{path.relative_to(ROOT).as_posix()} is missing, but the documented regeneration '
                f'passes it to gen_ae_to_se_map.py; drop it from OVERRIDE_FILES or restore it '
                f'rather than leaving this check covering nothing')
            continue

        rows = overrides(name)
        contributed[name] = len(rows)
        checked += len(rows)

        # 1. One entry per id. The reader is `table[id] = offset`, so a repeat is
        #    resolved by file order - silently, and differently if the file is
        #    ever sorted.
        seen: dict[int, list[int]] = {}
        for number, ae_id, _rva in rows:
            seen.setdefault(ae_id, []).append(number)
        for ae_id, numbers in sorted(seen.items()):
            if len(numbers) > 1:
                failures.append(
                    f'{path.relative_to(ROOT).as_posix()}: id {ae_id} appears on line(s) '
                    f'{", ".join(map(str, numbers))}; the reader keeps the last one, so the value '
                    f'that ships depends on file order')

        for number, ae_id, rva in rows:
            key = f'{name}:{ae_id}'

            # 2. Every RVA is a function start in the library the client loads -
            #    except the locators that live past .text, which are data by
            #    construction.
            if key not in ALLOWED_NON_START and rva not in starts and rva <= text_end:
                failures.append(
                    f'{path.relative_to(ROOT).as_posix()}:{number}: id {ae_id} maps to '
                    f'0x{rva:x}, which is inside .text but is not a function start in '
                    f'{SE_LIBRARY.name} - a call through it lands mid-function')

            # 3. The shipped map is generated from these files, so an id they
            #    carry must be in it with the same value - unless it is the one
            #    the README says is deliberately kept out.
            #
            #    An empty map is recorded once as a failure below; skipping the
            #    rows here keeps that one failure from being repeated per row.
            if not shipped_map:
                continue
            if ae_id not in shipped_map:
                if key not in ALLOWED_ABSENT:
                    failures.append(
                        f'{path.relative_to(ROOT).as_posix()}:{number}: id {ae_id} is not in '
                        f'{SHIPPED_MAP.name}, but the map is generated from this file; either the '
                        f'map was not regenerated or the id was dropped from it')
                continue
            if shipped_map[ae_id] != rva:
                failures.append(
                    f'{path.relative_to(ROOT).as_posix()}:{number}: id {ae_id} says 0x{rva:x} but '
                    f'the shipped map has 0x{shipped_map[ae_id]:x}; the map is generated from this '
                    f'file, so one of the two was regenerated without the other')

    if not shipped_map:
        failures.append(
            f'{SHIPPED_MAP.relative_to(ROOT).as_posix()} is missing or empty, so no override value '
            f'was compared against what ships; the map is generated from these files and is tracked '
            f'here, so an empty one means it moved or was truncated rather than that the values '
            f'agree')

    # A scanned file that contributes nothing, or an exemption that no longer
    # matches a row, outlives its reason and silently narrows this check.
    for name in OVERRIDE_FILES:
        if (OVERRIDE_DIR / name).is_file() and contributed.get(name, 0) == 0:
            failures.append(
                f'{name} contributed no override row; either it was emptied or its format changed, '
                f'in which case this check is silently covering nothing there')
    for key, reason in {**ALLOWED_NON_START, **ALLOWED_ABSENT}.items():
        name, _, raw_id = key.partition(':')
        ids = {ae_id for _n, ae_id, _r in overrides(name)}
        if int(raw_id) not in ids:
            failures.append(
                f'{name} no longer lists id {raw_id}, but this gate exempts it ({reason}); drop the '
                f'exemption rather than leaving it to cover nothing')

    return checked


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()

    if args.list:
        print('checked:')
        print('  every id in every override file appears once')
        print(f'  every RVA is a function start in {SE_LIBRARY.name} (or a locator past .text)')
        print(f'  every value agrees with {SHIPPED_MAP.name}')
        total = 0
        for name in OVERRIDE_FILES:
            rows = overrides(name)
            total += len(rows)
            print(f'    {name:<26} {len(rows):>5} row(s), '
                  f'{len({i for _n, i, _r in rows})} distinct id(s)')
        print(f'  {total} row(s) total')
        return 0

    failures: list[str] = []
    warnings: list[str] = []
    checked = check(failures, warnings)

    if warnings:
        for warning in warnings:
            print(f'  note: {warning}')

    if failures:
        print(f'AE-TO-SE OVERRIDE CHECK FAILED ({len(failures)})')
        for failure in failures:
            print(f'  - {failure}')
        return 1

    print('AE-TO-SE OVERRIDE CHECK OK')
    print(f'  {checked} override row(s) across {len(OVERRIDE_FILES)} file(s) validated against '
          f'{SE_LIBRARY.name} and the shipped map')
    return 0


if __name__ == '__main__':
    sys.exit(main())

#!/usr/bin/env python3
"""Hold every shipped AE-to-SE map to the id gap its runtime is declared to have.

A 1.5.x runtime does not load an AE address library; it loads
`version-<version>.bin` plus a translation table,
`versionlib-ae-to-se-<version>.map`, because the two id namespaces differ
(VersionDb::Load). Ten of each ship, and an id the table does not carry resolves
to the zero-returning stub: every call through it returns 0 instead of running.

Only the 1.5.97 map was ever accounted for - Tools/missing_1_5_97_ids.txt
declares its gap and check_docs.py compares that declaration against that one
map - so the other nine were unlooked at. That is how id 16113
(ExtraContainerChanges::Data::GetArmor) came to be missing from three of them
while the other seven carry it: the maps for 1.5.3, 1.5.16 and 1.5.23 were
generated by joining AE symbol names to SE ones, this symbol had no counterpart
in those three name tables, and nothing compared the results.

The rule is therefore "every shipped map's gap is exactly what its runtime is
declared to have", and the declaration is Tools/missing_ids_by_runtime.tsv. Two
directions are checked, because both are defects:

  * an id the map does not carry and nothing declares - the 16113 shape, an
    invisible degradation on one runtime;
  * an id declared but present - the declaration has outlived the gap, and a
    reader would still be told the runtime cannot resolve it.

The per-runtime rows are additionally bound to the code. A declared gap is only
harmless while the call sites that reach it do not act on the stub's zero, and
"does not act on it" is not decidable in general, so the bindings whose
consequence was judged are listed explicitly and this checks that the guard is
still there and still names the same id. A per-runtime row with no judged
binding fails rather than passing silently.

    python Tools/Scripts/check_map_coverage.py          # the gate
    python Tools/Scripts/check_map_coverage.py --list   # show what is checked
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'Tools' / 'Scripts'))

from gen_ae_to_se_map import collect_codebase_ids, parse_bin, parse_overrides  # noqa: E402

LIB_DIR = ROOT / 'GameFiles' / 'Skyrim' / 'SKSE' / 'Plugins'
DECLARATION = ROOT / 'Tools' / 'missing_ids_by_runtime.tsv'

# The map the others are compared against. It is the one the override table
# targets and the one Tools/ida holds evidence for, so it is the reference the
# per-build translations were derived from.
REFERENCE = '1-5-97-0'

# Bindings reached through an id that a shipped runtime does not map, whose
# consequence was read and judged safe. Each entry is
#   id -> (file, guard, note)
# where `guard` is a function whose body must name the same id, so the guard
# cannot be dropped or repointed without this failing.
#
# The rule for adding one: find the site that resolves the id, decide what the
# stub's zero makes it do, and either guard it or write down why the answer does
# not matter. Only ids declared per-runtime need an entry; the '*' rows are the
# subject of Tools/missing_1_5_97_ids.txt, which records the same judgement per
# id in prose.
JUDGED: dict[int, tuple[str, str, str]] = {
    16113: (
        'Code/client/Games/Skyrim/ExtraData/ExtraContainerChanges.cpp',
        'CanQueryArmor',
        'GetArmor can only answer nullptr, and Actor::IsWearingBodyPiece() reads '
        'that as "not wearing a body piece"; InventoryService::RunNakedNPCBugChecks '
        're-dresses the actor on it. CanQueryArmor() is what the call site asks first.',
    ),
}

VERSIONED_MAP = re.compile(r'^versionlib-ae-to-se-(.+)\.map$')
VERSIONED_LIB = re.compile(r'^version-(.+)\.bin$')
# The generic fallback name VersionDb::Load tries when the versioned map is
# absent. It is not a runtime's map, so it is only reported if it ships.
GENERIC_MAP = 'versionlib-ae-to-se.map'


def runtime_maps() -> tuple[dict[str, pathlib.Path], dict[str, pathlib.Path]]:
    """(runtime -> map, runtime -> library) for the versioned files that ship."""
    maps: dict[str, pathlib.Path] = {}
    libs: dict[str, pathlib.Path] = {}
    if not LIB_DIR.is_dir():
        return maps, libs
    for path in sorted(LIB_DIR.iterdir()):
        if not path.is_file():
            continue
        m = VERSIONED_MAP.match(path.name)
        if m:
            maps[m.group(1)] = path
            continue
        m = VERSIONED_LIB.match(path.name)
        if m and not path.name.startswith('versionlib-'):
            libs[m.group(1)] = path
    return maps, libs


def declaration() -> list[tuple[str, int, str]]:
    """(runtime, ae_id, why) for every row; runtime '*' means every runtime."""
    rows: list[tuple[str, int, str]] = []
    if not DECLARATION.is_file():
        return rows
    for line in DECLARATION.read_text(encoding='utf-8').splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        parts = line.split('\t')
        if len(parts) < 2:
            continue
        try:
            rows.append((parts[0].strip(), int(parts[1], 0), parts[2].strip() if len(parts) > 2 else ''))
        except ValueError:
            continue
    return rows


def guarded_ids() -> list[str]:
    """Every id named inside a JUDGED binding's guard function."""
    out: list[str] = []
    for ae_id, (rel, guard, _note) in sorted(JUDGED.items()):
        path = ROOT / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding='utf-8', errors='ignore')
        start = text.find(f'{guard}(')
        if start < 0:
            continue
        # Bracket-match the body, so the id has to appear in the guard's own
        # body rather than anywhere in the file.
        depth = 0
        end = start
        for i in range(text.find('{', start), len(text)):
            if text[i] == '{':
                depth += 1
            elif text[i] == '}':
                depth -= 1
                if depth == 0:
                    end = i
                    break
        body = text[start:end]
        if re.search(rf'\b{ae_id}\b', body):
            out.append(f'{rel}:{guard}:{ae_id}')
    return out


def check_agreement(failures: list[str]) -> int:
    """Every map must name the same pre-AE symbol for the same AE id.

    Values cannot be compared across maps: each carries the RVA of its own build,
    and adjacent builds legitimately disagree (id 16113 is 0x1e7750 on 1.5.39,
    0x1e7760 on 1.5.50 and 0x1e7570 from 1.5.73). What they must agree on is
    *which* pre-AE id that RVA is, because that is what the translation consumes:
    Gen_se_map_from_history translates through the pre-AE namespace, and the
    libraries are injective in both directions, so the pre-AE id is recoverable
    from either side.

    This is what catches a row that is merely wrong - a value that is a real
    function start, in the right library, and still not the function the AE id
    names. Comparing values cannot see that; comparing symbols can. It is also
    why id 16113 is absent from three maps rather than carrying a neighbour's
    RVA: pre-AE id 15873, the one the other seven translate from, does not exist
    in version-1-5-3-0/16-0/23-0.bin at all, so there was no value to emit.
    """
    maps, libs = runtime_maps()
    if REFERENCE not in maps or REFERENCE not in libs:
        failures.append(
            f'the reference runtime {REFERENCE} is not shipped as a map/library pair, so the maps '
            f'cannot be compared against the one the translations were derived from')
        return 0

    # RVA -> pre-AE id per library. The map generator asserts both libraries are
    # injective; this whole check rests on it, so verify it here instead of
    # trusting the claim.
    back: dict[str, dict[int, int]] = {}
    for runtime, path in sorted(libs.items()):
        table = parse_bin(path)
        inv: dict[int, int] = {}
        clashing = []
        for ae_id, offset in table.items():
            if offset in inv:
                clashing.append(offset)
            inv.setdefault(offset, ae_id)
        if clashing:
            failures.append(
                f'{path.name} assigns one offset to more than one id ({len(clashing)} offset(s), '
                f'e.g. 0x{clashing[0]:x}); the per-build translation is not reversible, so no map '
                f'built from it can be checked')
            continue
        back[runtime] = inv

    reference_map = parse_overrides(maps[REFERENCE])
    reference_back = back.get(REFERENCE, {})
    if not reference_map or not reference_back:
        failures.append(f'{maps[REFERENCE].name} could not be read against {libs[REFERENCE].name}')
        return 0

    # Both libraries assign one offset per id, so a map built from them cannot
    # name two ids for one offset either - and the generator refuses to write
    # one. Two AE ids sharing an RVA is how a mistranslated row looks when the
    # wrong value came from a neighbouring symbol.
    for runtime, path in sorted(maps.items()):
        claimed: dict[int, int] = {}
        for ae_id, offset in sorted(parse_overrides(path).items()):
            if offset in claimed:
                failures.append(
                    f'{path.name}: ids {claimed[offset]} and {ae_id} both map to 0x{offset:x}, so one '
                    f'of them calls the other\'s function')
            claimed.setdefault(offset, ae_id)

    compared = 0
    for runtime in sorted(maps):
        if runtime == REFERENCE or runtime not in back:
            continue
        path = maps[runtime]
        table = parse_overrides(path)
        mismatched = 0
        for ae_id in sorted(set(reference_map) & set(table)):
            offset_here = table[ae_id]
            offset_ref = reference_map[ae_id]
            here, there = back[runtime].get(offset_here), reference_back.get(offset_ref)
            if here is None or there is None:
                # Not an offset either library names, so there is no symbol to
                # compare; check 130.4's coverage rule is what rejects those.
                continue
            compared += 1
            if here != there:
                mismatched += 1
                if mismatched <= 3:
                    failures.append(
                        f'{path.name}: id {ae_id} names pre-AE id {here} (0x{offset_here:x}), but '
                        f'{maps[REFERENCE].name} names pre-AE id {there} (0x{offset_ref:x}) for the '
                        f'same AE id; one of the two was translated from something else')
        if mismatched > 3:
            failures.append(f'{path.name}: {mismatched} id(s) disagree with {maps[REFERENCE].name} about which pre-AE symbol they name')

    if compared == 0:
        failures.append(
            'no id was compared between any two maps, so the agreement rule covered nothing')
    return compared


def resolved_ids(rel: str) -> set[int]:
    """The ids a file resolves through POINTER_SKYRIMSE, as the collector sees them."""
    path = ROOT / rel
    if not path.is_file():
        return set()
    text = path.read_text(encoding='utf-8', errors='ignore')
    return {int(m) for m in re.findall(r'POINTER_SKYRIMSE\s*\(\s*[^,]+,\s*[^,]+,\s*(\d+)\s*\)', text)}


def check(failures: list[str], warnings: list[str]) -> int:
    ids = collect_codebase_ids()
    if not ids:
        failures.append(
            'collect_codebase_ids() returned no id at all, so every map would agree with every '
            'declaration vacuously; the client sources are missing or the collector changed shape')
        return 0

    maps, libs = runtime_maps()
    if not maps:
        failures.append(
            f'no versionlib-ae-to-se-<version>.map under '
            f'{LIB_DIR.relative_to(ROOT).as_posix()}; there is nothing left to check, which is not '
            f'the same as everything being fine')
        return 0
    if not libs:
        failures.append(f'no pre-AE version-<version>.bin library under {LIB_DIR.relative_to(ROOT).as_posix()}')

    for runtime in sorted(set(libs) - set(maps)):
        failures.append(
            f'{libs[runtime].name} ships with no versionlib-ae-to-se-{runtime}.map; the client '
            f'loads the library and then cannot translate a single id through it')
    for runtime in sorted(set(maps) - set(libs)):
        failures.append(
            f'{maps[runtime].name} ships with no version-{runtime}.bin library; no runtime can '
            f'load that pair')

    if (LIB_DIR / GENERIC_MAP).is_file():
        warnings.append(
            f'{GENERIC_MAP} ships as well; it is the fallback VersionDb::Load tries when the '
            f'versioned map is absent, and this gate does not cover it')

    rows = declaration()
    if not rows:
        failures.append(
            f'{DECLARATION.relative_to(ROOT).as_posix()} declares no row; every map would then be '
            f'required to have an empty gap')
        return 0

    common = {ae_id for runtime, ae_id, _why in rows if runtime == '*'}
    per_runtime: dict[str, set[int]] = {}
    for runtime, ae_id, _why in rows:
        if runtime != '*':
            per_runtime.setdefault(runtime, set()).add(ae_id)

    # A runtime name that matches no shipped map is a typo, and a typo is
    # indistinguishable from "declared, but nothing to check it against".
    for runtime in sorted(per_runtime):
        if runtime not in maps:
            failures.append(
                f'{DECLARATION.relative_to(ROOT).as_posix()}: row for runtime {runtime}, which no '
                f'shipped map matches ({", ".join(sorted(maps))})')

    # The per-runtime rows are the ones whose consequence had to be judged.
    for runtime, declared in sorted(per_runtime.items()):
        for ae_id in sorted(declared):
            if ae_id not in JUDGED:
                failures.append(
                    f'{DECLARATION.relative_to(ROOT).as_posix()}: id {ae_id} is declared missing on '
                    f'{runtime} but no binding is judged for it in this gate\'s JUDGED table; read '
                    f'what the stub\'s zero makes every call site through it do, guard the ones '
                    f'that act on it, then add the entry')

    checked = 0
    for runtime in sorted(maps):
        path = maps[runtime]
        carried = set(parse_overrides(path))
        gap = ids - carried
        declared = common | per_runtime.get(runtime, set())
        checked += 1

        unlooked = sorted(gap - declared)
        if unlooked:
            failures.append(
                f'{path.name} does not carry {len(unlooked)} id(s) the client resolves and nothing '
                f'declares: {unlooked}; on {runtime} each of them resolves to the zero-returning '
                f'stub, so either produce the row or declare it in '
                f'{DECLARATION.relative_to(ROOT).as_posix()}')

        stale = sorted(declared - gap)
        if stale:
            failures.append(
                f'{DECLARATION.relative_to(ROOT).as_posix()} declares {stale} missing from '
                f'{runtime}, but {path.name} carries them; drop the declaration or fix the map')

    # A guard that stopped naming its id, or moved out of the file, leaves the
    # declaration above standing on nothing. And the guard is only asking about
    # the right thing while the file it lives in resolves that same id: the
    # probe and the call it protects are two statements of one fact.
    live = guarded_ids()
    for ae_id, (rel, guard, note) in sorted(JUDGED.items()):
        expected = f'{rel}:{guard}:{ae_id}'
        if expected not in live:
            failures.append(
                f'{rel}: no {guard} body naming id {ae_id}; this gate relies on it to keep the '
                f'declared gap harmless ({note})')
            continue
        resolved = resolved_ids(rel)
        if ae_id not in resolved:
            failures.append(
                f'{rel}: {guard} guards id {ae_id}, but the file resolves '
                f'{sorted(resolved)} through POINTER_SKYRIMSE; the guard is asking about one id '
                f'while the call site uses another')

    if not live:
        failures.append('no judged binding contributed anything, so this gate checked no call site')

    check_agreement(failures)

    return checked


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument('--list', action='store_true')
    args = parser.parse_args()

    if args.list:
        maps, libs = runtime_maps()
        print('checked:')
        print('  every shipped pre-AE library has its map, and every map its library')
        print(
            '  every map\'s gap = the client ids it does not carry, exactly as '
            f'{DECLARATION.relative_to(ROOT).as_posix()} declares it')
        print('  every per-runtime row has a judged binding whose guard still names the id')
        print('  every judged guard names an id its own file resolves through POINTER_SKYRIMSE')
        print(f'  every map names the same pre-AE symbol as {REFERENCE} for every AE id they share')
        print(f'  libraries: {len(libs)}  maps: {len(maps)}')
        for runtime in sorted(maps):
            carried = len(parse_overrides(maps[runtime]))
            print(f'    {runtime:<12} {maps[runtime].name}  {carried} row(s)')
        rows = declaration()
        print(f'  {len(rows)} declared row(s): '
              f'{len({i for r, i, _w in rows if r == "*"})} shared, '
              f'{len(rows) - len([1 for r, _i, _w in rows if r == "*"])} per-runtime')
        return 0

    failures: list[str] = []
    warnings: list[str] = []
    checked = check(failures, warnings)

    for warning in warnings:
        print(f'  note: {warning}')

    if failures:
        print(f'MAP COVERAGE CHECK FAILED ({len(failures)})')
        for failure in failures:
            print(f'  - {failure}')
        return 1

    print('MAP COVERAGE CHECK OK')
    print(f'  {checked} shipped pre-AE map(s) match their declared id gap, '
          f'{len(JUDGED)} judged binding(s) still guard the ids declared per runtime')
    return 0


if __name__ == '__main__':
    sys.exit(main())
